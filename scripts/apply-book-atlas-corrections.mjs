/**
 * Applies scripts/book-atlas-corrections.mjs to the generated atlas in place, for when the private
 * build inputs (docs/agent-atlas/book-sources) are not at hand. Safe to run more than once:
 *   node scripts/apply-book-atlas-corrections.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { juniorUnits, companionByLesson, cppUnitPages, correctCppWords, CLOSE_UP_B1_GRAMMAR_12 } from './book-atlas-corrections.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = path.join(root, 'features/bookAtlas/data');
const readJson = name => JSON.parse(fs.readFileSync(path.join(dataDir, name + '.json'), 'utf8'));
const writeJson = (name, data) => fs.writeFileSync(path.join(dataDir, name + '.json'), JSON.stringify(data) + '\n');
const { BOOK_ATLAS } = await import(path.join(root, 'features/bookAtlas.data.mjs'));
const atlas = structuredClone(BOOK_ATLAS);

for (let level = 1; level <= 3; level++) {
    const data = readJson('cpp' + level);
    correctCppWords(level, data.units);
    writeJson('cpp' + level, data);
    const book = atlas.find(b => b.id === 'primary-path-' + level);
    const firstWb = Math.min(...(data.units['1'] || []).filter(w => w.component === 'wb' && w.page > 0).map(w => w.page));
    book.units.forEach((u, i) => {
        u.pages = { ...u.pages, ...cppUnitPages(i, Number.isFinite(firstWb) ? firstWb : null) };
        u.pageRange = u.pages.sb;
    });
}
{
    const data = readJson('yeti2');
    data.companion = companionByLesson(data.units, data.companion);
    writeJson('yeti2', data);
}
for (const book of atlas) {
    const curated = juniorUnits(book.id);
    if (curated) book.units = book.units.map(u => {
        const c = curated.find(x => x.n === u.n);
        return c ? { ...u, title: c.title, theme: c.theme, grammar: c.grammar ?? u.grammar, pages: c.pages, pageRange: c.pages.sb } : u;
    });
    if (book.id === 'close-up-b1') book.units.find(u => u.n === 12).grammar = CLOSE_UP_B1_GRAMMAR_12;
}
fs.writeFileSync(path.join(root, 'features/bookAtlas.data.mjs'), '// Generated by scripts/build-book-atlas.mjs. Source dates and provenance are per book.\nexport const BOOK_ATLAS = ' + JSON.stringify(atlas, null, 2) + ';\nexport default BOOK_ATLAS;\n');
console.log('Book Atlas corrections applied.');
