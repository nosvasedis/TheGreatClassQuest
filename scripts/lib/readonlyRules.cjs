'use strict';

// Builds the "read-only" Firestore rules used while the database moves (tools/DATA_MOVE_TO_EUROPE.md).
// Every read rule is kept exactly as written; every write rule is removed. Rules only ever
// grant access (an allow never takes access away), so a request that no allow statement grants
// is refused: reads behave as today, and every create / update / delete is refused.
//
//   allow read: if A;                  -> kept as is
//   allow get, list: if B;             -> kept as is
//   allow create, update: if C;        -> removed
//   allow read, write: if D;           -> allow read: if D;
//
// A small scanner finds every `allow` outside comments and strings, wherever it sits on a line,
// and the result is checked again before it is returned. Tests: tests/data-move.test.js and
// tests/emulator/data-move-readonly-rules.cjs.

const READ_METHODS = new Set(['read', 'get', 'list']);
const WRITE_METHODS = new Set(['write', 'create', 'update', 'delete']);

// Yields the index of every `allow` keyword that starts a statement, skipping comments/strings.
function findAllowKeywords(text) {
  const found = [];
  let quote = null;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quote) {
      if (ch === '\\') { i += 1; continue; }
      if (ch === quote) quote = null;
      continue;
    }
    if (ch === '/' && text[i + 1] === '/') { const nl = text.indexOf('\n', i); i = nl === -1 ? text.length : nl; continue; }
    if (ch === '/' && text[i + 1] === '*') { const close = text.indexOf('*/', i + 2); i = close === -1 ? text.length : close + 1; continue; }
    if (ch === '"' || ch === "'") { quote = ch; continue; }
    if (text.startsWith('allow', i) && !/[A-Za-z0-9_$.]/.test(text[i - 1] || '') && /\s/.test(text[i + 5] || '')) {
      found.push(i);
      i += 4;
    }
  }
  return found;
}

// The end of a statement: the first ';' outside strings, brackets and comments.
function statementEnd(text, from) {
  let depth = 0;
  let quote = null;
  for (let i = from; i < text.length; i += 1) {
    const ch = text[i];
    if (quote) {
      if (ch === '\\') { i += 1; continue; }
      if (ch === quote) quote = null;
      continue;
    }
    if (ch === '/' && text[i + 1] === '/') { const nl = text.indexOf('\n', i); i = nl === -1 ? text.length : nl; continue; }
    if (ch === '/' && text[i + 1] === '*') { const close = text.indexOf('*/', i + 2); i = close === -1 ? text.length : close + 1; continue; }
    if (ch === '"' || ch === "'") { quote = ch; continue; }
    if (ch === '(' || ch === '[' || ch === '{') depth += 1;
    else if (ch === ')' || ch === ']' || ch === '}') depth -= 1;
    else if (ch === ';' && depth === 0) return i;
  }
  return -1;
}

// Every allow statement: { start, end, methods, rest } where rest is ": if ...;" (or ";").
function parseAllows(text) {
  return findAllowKeywords(text).map((start) => {
    const end = statementEnd(text, start);
    if (end === -1) throw new Error(`Unterminated allow statement at offset ${start}`);
    const body = text.slice(start + 'allow'.length, end + 1);
    const colon = body.indexOf(':');
    const head = colon === -1 ? body.slice(0, -1) : body.slice(0, colon);
    const methods = head.split(',').map((m) => m.trim()).filter(Boolean);
    const unknown = methods.filter((m) => !READ_METHODS.has(m) && !WRITE_METHODS.has(m));
    if (!methods.length || unknown.length) throw new Error(`Unknown rule method(s) at offset ${start}: ${head.trim()}`);
    return { start, end, methods, rest: colon === -1 ? ';' : body.slice(colon) };
  });
}

function makeReadonlyRules(source) {
  const text = String(source).replace(/\r\n/g, '\n');
  const stats = { kept: 0, narrowed: 0, removed: 0 };
  let out = '';
  let last = 0;
  for (const allow of parseAllows(text)) {
    out += text.slice(last, allow.start);
    const reads = allow.methods.filter((m) => READ_METHODS.has(m));
    if (reads.length === allow.methods.length) {
      out += text.slice(allow.start, allow.end + 1);
      stats.kept += 1;
    } else if (reads.length) {
      out += `allow ${reads.join(', ')}${allow.rest}`;
      stats.narrowed += 1;
    } else {
      out += '/* write rule removed while the database moves */';
      stats.removed += 1;
    }
    last = allow.end + 1;
  }
  out += text.slice(last);
  const rules = [
    '// GENERATED by scripts/lib/readonlyRules.cjs from firestore.rules. Do not edit.',
    '// Used only while the database moves: every read rule as in firestore.rules, no writes.',
    out,
  ].join('\n');
  // Check the result again: no statement may grant any write.
  const leftover = parseAllows(rules).filter((a) => a.methods.some((m) => WRITE_METHODS.has(m)));
  if (leftover.length) throw new Error(`Read-only rules still allow writes at offsets ${leftover.map((a) => a.start).join(', ')}`);
  return { rules, stats };
}

// Every allow statement in a rules text, as { methods, condition } (used by the tests).
function listAllows(source) {
  const text = String(source).replace(/\r\n/g, '\n');
  return parseAllows(text).map((a) => ({
    methods: a.methods,
    condition: a.rest.replace(/^\s*:\s*/, '').replace(/;$/, '').trim(),
  }));
}

module.exports = { makeReadonlyRules, listAllows, READ_METHODS, WRITE_METHODS };
